"""Build the OpenStreetMap terminal list for Indian airports (data © OpenStreetMap contributors,
ODbL 1.0, credited wherever it's shown).

Usage:
    python scripts/build_osm_terminals.py

Reads the airport list from apps/api/data/airports.yaml, asks the public Overpass API once for
every `aeroway=terminal` inside each Indian aerodrome that has an IATA tag, and writes
apps/api/data/osm_terminals.yaml.

Mechanical rules only (nothing is inferred):
  - keep terminals with a name; drop unnamed outlines
  - drop non-passenger buildings: names containing cargo, freight, logistics, courier,
    general aviation or VIP
  - one entry per name per airport, preferring a relation, then a way, then a node
Names and refs are copied as mapped. Roles (domestic/international) are not derived.
"""

import json
import re
import sys
from datetime import UTC, datetime
from pathlib import Path

import httpx
import yaml

ROOT = Path(__file__).resolve().parents[1]
AIRPORTS = ROOT / "apps/api/data/airports.yaml"
OUT = ROOT / "apps/api/data/osm_terminals.yaml"
OVERPASS = "https://overpass-api.de/api/interpreter"
USER_AGENT = "AeroGuide-build (+https://github.com/NagbhushanPai/AeroGuide)"
INDIA_BBOX = "6,68,37.5,97.6"  # south, west, north, east

QUERY = f"""[out:json][timeout:180];
nwr["aeroway"="aerodrome"]["iata"]({INDIA_BBOX})->.aero;
foreach.aero->.a(
  .a out tags center;
  .a map_to_area->.ar;
  nwr(area.ar)["aeroway"="terminal"];
  out tags center;
);
"""
NOT_PASSENGER = re.compile(r"cargo|freight|logistics|courier|general aviation|\bvip\b", re.I)
TYPE_RANK = {"relation": 0, "way": 1, "node": 2}


def point(element: dict[str, object]) -> tuple[float, float] | None:
    c = element.get("center") or element
    if isinstance(c, dict) and "lat" in c and "lon" in c:
        return round(float(c["lat"]), 5), round(float(c["lon"]), 5)
    return None


def select(elements: list[dict[str, object]], iatas: set[str]) -> list[dict[str, object]]:
    current: str | None = None
    best: dict[tuple[str, str], dict[str, object]] = {}
    for e in elements:
        tags = e.get("tags") or {}
        assert isinstance(tags, dict)
        if tags.get("aeroway") == "aerodrome":
            code = str(tags.get("iata", "")).strip().upper()
            current = code if code in iatas else None
            continue
        if current is None or tags.get("aeroway") != "terminal":
            continue
        name = str(tags.get("name:en") or tags.get("name") or "").strip()
        where = point(e)
        if not name or NOT_PASSENGER.search(name) or where is None:
            continue
        row = {
            "iata": current,
            "osm": f"{e['type']}/{e['id']}",
            "name": name,
            "ref": (str(tags["ref"]).strip() or None) if tags.get("ref") else None,
            "lat": where[0],
            "lon": where[1],
            "_rank": TYPE_RANK.get(str(e["type"]), 3),
        }
        key = (current, name.lower())
        if key not in best or row["_rank"] < best[key]["_rank"]:  # type: ignore[operator]
            best[key] = row
    rows = sorted(best.values(), key=lambda r: (str(r["iata"]), str(r["name"])))
    for r in rows:
        r.pop("_rank")
    return rows


def write(rows: list[dict[str, object]], today: str) -> None:
    lines = [
        "# GENERATED by scripts/build_osm_terminals.py from OpenStreetMap (ODbL 1.0).",
        "# Do not edit by hand: rerun the script. Fix mistakes in OpenStreetMap itself.",
        "source: openstreetmap",
        f"retrieved_at: {today}",
        "terminals:" if rows else "terminals: []",
    ]
    for r in rows:
        first = True
        for key in ("iata", "osm", "name", "ref", "lat", "lon"):
            value = r[key]
            text = "null" if value is None else (
                str(value) if isinstance(value, float) else json.dumps(value, ensure_ascii=False)
            )
            lines.append(f"{'  - ' if first else '    '}{key}: {text}")
            first = False
    OUT.write_text("\n".join(lines) + "\n", "utf-8")


def main() -> None:
    iatas = {a["iata"] for a in yaml.safe_load(AIRPORTS.read_text("utf-8"))["airports"]}
    r = httpx.post(OVERPASS, data={"data": QUERY}, headers={"User-Agent": USER_AGENT}, timeout=240)
    r.raise_for_status()
    rows = select(r.json()["elements"], iatas)
    write(rows, datetime.now(UTC).date().isoformat())
    airports = len({r["iata"] for r in rows})
    print(f"wrote {len(rows)} terminals at {airports} airports to {OUT.relative_to(ROOT)}")


if __name__ == "__main__":
    if len(sys.argv) != 1:
        sys.exit(__doc__)
    main()
